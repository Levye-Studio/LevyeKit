bool GenerateCommand::Execute(const fs::path& projectDirectory, std::string_view type,
                              std::string_view name, const GenerateOptions& options) {
  const bool isClass = type == "class";
  const bool isSource = type == "source";
  const bool isHeader = type == "header";
  const bool isFolder = type == "folder";
  if (!isClass && !isSource && !isHeader && !isFolder) {
    std::cerr << "[Levye] Unknown generator: " << type << '\n';
    return false;
  }
  const fs::path relative{std::string(name)};
  if (!ValidPath(relative)) {
    std::cerr << "[Levye] Invalid generation path.\n";
    return false;
  }
  const fs::path sourceRoot = projectDirectory / "Source";
  if (!SafePath(projectDirectory, "Source") || !SafePath(sourceRoot, relative)) {
    std::cerr << "[Levye] Symlink or unsafe path.\n";
    return false;
  }
  const fs::path destination = sourceRoot / relative;
  if (isFolder) {
    std::error_code ec;
    if (fs::exists(destination)) {
      if (options.force && fs::is_directory(destination)) return true;
      std::cerr << "[Levye] Folder already exists.\n";
      return false;
    }
    if (!fs::create_directories(destination, ec) || ec) {
      std::cerr << "[Levye] Cannot create folder: " << ec.message() << '\n';
      return false;
    }
    std::cout << "[Levye] Created " << destination.lexically_relative(projectDirectory) << '\n';
    return true;
  }

  const std::string filename = relative.filename().string();
  fs::path header = destination;
  header += ".hpp";
  fs::path source = destination;
  source += ".cpp";
  std::vector<PendingFile> changes;
  if (isClass) {
    const std::string h = "#pragma once\n\nclass " + filename + " {\n public:\n  " + filename +
                          "() = default;\n  ~" + filename + "() = default;\n};\n";
    changes.push_back({header, h, options.force});
    changes.push_back({source, "#include \"" + filename + ".hpp\"\n", options.force});
  } else if (isSource) {
    changes.push_back({source, "// " + filename + ".cpp\n", options.force});
  } else {
    changes.push_back({header, "#pragma once\n", options.force});
  }

  for (const auto& file : changes) {
    if (!SafePath(sourceRoot, file.path.lexically_relative(sourceRoot))) {
      std::cerr << "[Levye] Unsafe output path.\n";
      return false;
    }
  }

  if ((isClass || isSource) && !options.noCMake) {
    CMakeMigrationPlan plan;
    std::string error;
    if (!ProjectCMakeMigration::Prepare(projectDirectory, plan, error)) {
      std::cerr << "[Levye] " << error << '\n';
      return false;
    }
    fs::path relativeSource = relative;
    relativeSource += ".cpp";
    std::string updatedManifest;
    if (!PrepareSourceRegistration(plan.sourceManifest, relativeSource, updatedManifest)) {
      std::cerr << "[Levye] Invalid or unsupported CMake source manifest.\n";
      return false;
    }
    if (plan.updateRoot)
      changes.push_back({projectDirectory / "CMakeLists.txt", plan.rootCMake, true});
    if (plan.createManifest || updatedManifest != plan.sourceManifest)
      changes.push_back({sourceRoot / "CMakeLists.txt", updatedManifest, !plan.createManifest});
  }

  std::error_code ec;
  fs::create_directories(destination.parent_path(), ec);
  if (ec) {
    std::cerr << "[Levye] Cannot create directories: " << ec.message() << '\n';
    return false;
  }
  std::string error;
  if (!CommitFiles(projectDirectory, changes, error)) {
    std::cerr << "[Levye] Generation failed: " << error << '\n';
    return false;
  }
  std::cout << "[Levye] Generated:\n";
  for (const auto& file : changes)
    std::cout << "  " << file.path.lexically_relative(projectDirectory) << '\n';
  return true;
}
