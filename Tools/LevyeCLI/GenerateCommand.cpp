bool IsIdentifier(std::string_view name) {
  if (name.empty()) return false;
  auto alpha = [](char c) { return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z'); };
  auto digit = [](char c) { return c >= '0' && c <= '9'; };
  if (!alpha(name.front()) && name.front() != '_') return false;
  for (char c : name)
    if (!alpha(c) && !digit(c) && c != '_') return false;
  return true;
}

bool ValidPath(const fs::path& path) {
  if (path.empty() || path.has_root_path()) return false;
  for (const auto& part : path) {
    if (!IsIdentifier(part.string())) return false;
  }
  return true;
}

bool ValidSourceEntry(std::string_view entry) {
  if (entry.empty() || entry.find('\\') != std::string_view::npos) return false;
  fs::path path{std::string(entry)};
  if (path.extension() != ".cpp" || path.has_root_path()) return false;
  path.replace_extension();
  return ValidPath(path);
}

bool SafePath(const fs::path& root, const fs::path& relative) {
  fs::path current = root;
  for (const auto& part : relative) {
    std::error_code ec;
    const auto status = fs::symlink_status(current, ec);
    if (ec && ec != std::errc::no_such_file_or_directory) return false;
    if (!ec && fs::is_symlink(status)) return false;
    current /= part;
  }
  std::error_code ec;
  const auto status = fs::symlink_status(current, ec);
  return (ec == std::errc::no_such_file_or_directory) || (!ec && !fs::is_symlink(status));
}

bool ParseEntries(std::string_view section, std::vector<std::string>& sources) {
  std::istringstream input{std::string(section)};
  std::string line;
  enum class State { Open, Entries, Closed };
  State state = State::Open;
  constexpr std::string_view prefix = "    \"${CMAKE_CURRENT_LIST_DIR}/";
  while (std::getline(input, line)) {
    if (!line.empty() && line.back() == '\r') line.pop_back();
    if (line.empty()) continue;
    if (state == State::Open) {
      if (line != "list(APPEND LEVYE_GAME_SOURCES") return false;
      state = State::Entries;
    } else if (state == State::Entries) {
      if (line == ")") {
        state = State::Closed;
        continue;
      }
      if (!line.starts_with(prefix) || !line.ends_with('"')) return false;
      std::string entry = line.substr(prefix.size(), line.size() - prefix.size() - 1);
      if (!ValidSourceEntry(entry)) return false;
      sources.push_back(std::move(entry));
    } else {
      return false;
    }
  }
  return state == State::Closed;
}

bool PrepareSourceRegistration(const std::string& original, const fs::path& relativeSource,
                               std::string& updated) {
  const std::string path = relativeSource.generic_string();
  if (!ValidSourceEntry(path)) return false;
  constexpr std::string_view begin = "# LEVYE_GENERATED_SOURCES_BEGIN";
  constexpr std::string_view end = "# LEVYE_GENERATED_SOURCES_END";
  const auto b = original.find(begin);
  const auto e = original.find(end);
  const bool marked = b != std::string::npos && e != std::string::npos;
  std::string prefix, suffix, section;
  if ((b == std::string::npos) != (e == std::string::npos)) return false;
  if (marked) {
    if (b >= e || original.find(begin, b + begin.size()) != std::string::npos ||
        original.find(end, e + end.size()) != std::string::npos)
      return false;
    if ((b > 0 && original[b - 1] != '\n') || (e > 0 && original[e - 1] != '\n') ||
        (b + begin.size() < original.size() && original[b + begin.size()] != '\n') ||
        (e + end.size() < original.size() && original[e + end.size()] != '\n'))
      return false;
    prefix = original.substr(0, b);
    suffix = original.substr(e + end.size());
    section = original.substr(b + begin.size(), e - b - begin.size());
  } else {
    const std::string legacyHeader =
        "# Additional game sources generated by Levye CLI.\n"
        "# Paths are relative to Source/.\n\n";
    if (!original.starts_with(legacyHeader)) return false;
    section = original.substr(legacyHeader.size());
    prefix = "# Additional game sources managed by Levye CLI.\n\n";
    suffix = "\n";
  }
  std::vector<std::string> sources;
  if (!ParseEntries(section, sources)) return false;
  sources.push_back(path);
  std::sort(sources.begin(), sources.end());
  sources.erase(std::unique(sources.begin(), sources.end()), sources.end());
  std::ostringstream out;
  out << begin << "\nlist(APPEND LEVYE_GAME_SOURCES\n";
  for (const auto& source : sources) out << "    \"${CMAKE_CURRENT_LIST_DIR}/" << source << "\"\n";
  out << ")\n" << end;
  updated = prefix + out.str() + suffix;
  return true;
}
